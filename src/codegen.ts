// Code generation: typed entity interfaces, event parameter types and
// handler registration helpers in <project>/generated/index.ts.

import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import type { AbiParameter } from "viem";
import { contractEvents } from "./abi.js";
import type { Config } from "./config.js";
import { loadSchema, tsType } from "./schema.js";

function paramType(p: AbiParameter): string {
  const t = p.type;
  const arr = t.match(/^(.*)\[\d*\]$/);
  if (arr) return `${paramType({ ...p, type: arr[1] } as AbiParameter)}[]`;
  if (t === "address" || t === "string" || t.startsWith("bytes")) return "string";
  if (t === "bool") return "boolean";
  const n = t.match(/^u?int(\d*)$/);
  if (n) return Number(n[1] || 256) <= 48 ? "number" : "bigint";
  if (t === "tuple" && "components" in p) {
    return `{ ${(p as any).components.map((c: AbiParameter, i: number) => `${c.name || `_${i}`}: ${paramType(c)}`).join("; ")} }`;
  }
  return "unknown";
}

export function generate(cfg: Config): string {
  const entities = loadSchema(cfg.schema);
  const events = contractEvents(cfg);
  const out: string[] = [
    "// Generated by `faster-index codegen`. Do not edit.",
    'import { register, type Event, type EntityOps } from "faster-index";',
    "",
  ];
  for (const e of entities) {
    out.push(`export interface ${e.name} {`);
    for (const f of e.fields) {
      if (f.derivedFrom) continue;
      out.push(`  ${f.name}${f.required ? "" : "?"}: ${tsType(f)}${f.required ? "" : " | null"};`);
    }
    out.push("}", "");
  }
  out.push("export interface Context {", "  chainId: number;", "  log: { info(...a: unknown[]): void; warn(...a: unknown[]): void; error(...a: unknown[]): void };");
  for (const e of entities) out.push(`  ${e.name}: EntityOps<${e.name}>;`);
  out.push("}", "");
  const byContract = new Map<string, typeof events>();
  for (const ev of events) byContract.set(ev.contract, [...(byContract.get(ev.contract) ?? []), ev]);
  for (const [c, evs] of byContract) {
    for (const ev of evs) {
      out.push(`export interface ${c}_${ev.name}_Params {`);
      ev.abi.inputs.forEach((p, i) => out.push(`  ${p.name || `_${i}`}: ${paramType(p)};`));
      out.push("}");
      out.push(`export type ${c}_${ev.name}_Event = Event<${c}_${ev.name}_Params>;`, "");
    }
    out.push(`export const ${c} = {`);
    for (const ev of evs) {
      out.push(
        `  ${ev.name}: {`,
        `    handler(fn: (args: { event: ${c}_${ev.name}_Event; context: Context }) => Promise<void> | void): void {`,
        `      register("${c}", "${ev.name}", fn as any);`,
        "    },",
        "  },",
      );
    }
    out.push("};", "");
  }
  return out.join("\n");
}

export function codegen(cfg: Config): string {
  const dir = join(cfg.root, "generated");
  mkdirSync(dir, { recursive: true });
  const path = join(dir, "index.ts");
  writeFileSync(path, generate(cfg));
  return path;
}
